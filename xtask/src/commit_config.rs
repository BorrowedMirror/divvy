//! Generates commitlint config and docs from `.commit-config.toml`.
use std::{collections::BTreeMap, fmt::Write as _, path::PathBuf};

use serde::Deserialize;

#[derive(Debug, Deserialize)]
pub struct CommitConfig {
    pub header_max_length: usize,
    pub types: BTreeMap<String, String>,
    pub scopes: BTreeMap<String, String>,
}

pub fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).parent().expect("workspace root").to_path_buf()
}

pub fn load() -> anyhow::Result<CommitConfig> {
    Ok(toml::from_str(&std::fs::read_to_string(root().join(".commit-config.toml"))?)?)
}

pub fn commitlintrc(c: &CommitConfig) -> serde_json::Value {
    let types: Vec<_> = c.types.keys().collect();
    let scopes: Vec<_> = c.scopes.keys().collect();
    serde_json::json!({
        "$comment": "GENERATED by `cargo xtask gen` from .commit-config.toml; do not edit.",
        "extends": ["@commitlint/config-conventional"],
        "rules": {
            "header-max-length": [2, "always", c.header_max_length],
            "type-enum": [2, "always", types],
            "scope-enum": [2, "always", scopes],
            "scope-case": [2, "always", "lower-case"],
            "subject-case": [2, "always", "lower-case"],
            "subject-full-stop": [2, "never", "."],
            "body-leading-blank": [2, "always"],
            "footer-leading-blank": [2, "always"]
        }
    })
}

pub fn markdown(c: &CommitConfig) -> String {
    let mut s = String::from(
        "<!-- GENERATED by `cargo xtask gen` from .commit-config.toml; do not edit. -->\n# Commit message guidelines\n\n",
    );
    let _ = writeln!(
        s,
        "Header: `<type>(<scope>): <summary>`, at most {} characters, imperative mood, lowercase, no trailing period.\nThe body explains **why**. Footers: `BREAKING CHANGE: <migration>`, `Fixes #<n>`.\nReverts: `revert: <original header>` with body `This reverts commit <SHA>.`\n\n## Types\n\n| Type | Description |\n| --- | --- |",
        c.header_max_length
    );
    for (k, v) in &c.types {
        let _ = writeln!(s, "| `{k}` | {v} |");
    }
    s.push_str("\n## Scopes\n\n| Scope | Description |\n| --- | --- |\n");
    for (k, v) in &c.scopes {
        let _ = writeln!(s, "| `{k}` | {v} |");
    }
    s
}

pub fn generate() -> anyhow::Result<()> {
    let c = load()?;
    let root = root();
    std::fs::write(root.join(".commitlintrc.json"), serde_json::to_string_pretty(&commitlintrc(&c))? + "\n")?;
    std::fs::create_dir_all(root.join("docs/contributing"))?;
    std::fs::write(root.join("docs/contributing/commit-message.md"), markdown(&c))?;
    Ok(())
}

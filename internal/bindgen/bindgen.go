// Package bindgen writes web/src/bindings.ts for the Go backend: the same `commands`, `events`
// and types the frontend imported from the tauri-specta file, now calling Wails.
//
// Commands are the exported methods of one bound service. Each becomes
// `commands.<lowerCamelName>(params...)`, calling the method through `Call.ByName` from
// `@wailsio/runtime`. A method returning `(T, error)` or just `error` resolves to
// `{status: "ok", data}` or `{status: "error", error}`, as tauri-specta's typedError did; a
// method without an error result resolves to its value. A leading `context.Context` parameter
// is supplied by Wails and is not part of the TypeScript signature.
//
// Events become `events.<name>.listen(cb)`, where cb receives `{payload}` like a Tauri event.
//
// Types are generated from the Go types by reflection, using their `json` tags. Types whose JSON
// is written by hand (string enums, serde-style tagged unions) have no Go shape reflection can
// see: their TypeScript goes in [Spec.Literal]. Doc comments are read from the Go source.
package bindgen

import (
	"bytes"
	"cmp"
	"context"
	"fmt"
	"go/ast"
	"go/doc"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"slices"
	"strings"
	"time"
	"unicode"
)

// Event is one event the backend emits.
type Event struct {
	// Name is the key in the generated `events` object (`priceReady`).
	Name string
	// Wire is the event name on the bus (`price-ready`).
	Wire string
	// Payload is the event's data type.
	Payload reflect.Type
}

// Spec describes what to generate.
type Spec struct {
	// Service is the bound service's struct type (not a pointer).
	Service reflect.Type
	// Events are the events the backend emits.
	Events []Event
	// Literal holds the TypeScript for types whose JSON reflection cannot describe.
	Literal map[reflect.Type]string
	// ModulePath and ModuleDir map Go package paths to source directories, for doc comments
	// and parameter names.
	ModulePath, ModuleDir string
}

// Generate returns the contents of bindings.ts.
func Generate(spec Spec) ([]byte, error) {
	g := &gen{spec: spec, named: map[string]reflect.Type{}, docs: map[string]*pkgDocs{}}
	methods, err := g.commands()
	if err != nil {
		return nil, err
	}
	var events []string
	for _, e := range spec.Events {
		ts, err := g.ref(e.Payload, ser)
		if err != nil {
			return nil, fmt.Errorf("event %s: %w", e.Name, err)
		}
		events = append(events, fmt.Sprintf("\t%s: makeEvent<%s>(%q),", e.Name, ts, e.Wire))
	}
	types, err := g.declarations()
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("/** Command name -> [bound Go method, argument names in order]. */\nconst METHODS: Record<string, [string, string[]]> = {\n")
	b.WriteString(strings.Join(g.methodTable, ""))
	b.WriteString("};\n\n")
	b.WriteString(transport)
	b.WriteString("/** Commands */\nexport const commands = {\n")
	for _, m := range methods {
		b.WriteString(m)
	}
	b.WriteString("};\n\n/** Events */\nexport const events = {\n")
	b.WriteString(strings.Join(events, "\n"))
	b.WriteString("\n};\n\n/* Types */\n")
	b.WriteString(types)
	b.WriteString(footer)
	return b.Bytes(), nil
}

const header = `// @ts-nocheck
// GENERATED by ` + "`go generate ./...`" + ` (cmd/bindgen) from the Go IPC service. Do not edit.
import { Call, Events } from "@wailsio/runtime";

`

const transport = `/**
 * How commands and events reach the backend. In the app this is Wails; tests and the browser
 * preview install an in-memory transport with [setTransport], keyed by the same command names.
 */
export type Transport = {
	invoke(cmd: string, args: Record<string, unknown>): Promise<unknown>;
	listen(event: string, cb: (payload: unknown) => void): Promise<() => void>;
};

const wails: Transport = {
	invoke: (cmd, args) => {
		const [method, names] = METHODS[cmd];
		return Call.ByName(method, ...names.map((n) => args[n]));
	},
	listen: (event, cb) => Promise.resolve(Events.On(event, (e: { data: unknown }) => cb(e.data))),
};

let transport: Transport = wails;

/** Replace the backend (tests, browser preview); null restores Wails. */
export function setTransport(t: Transport | null): void {
	transport = t ?? wails;
}

function invoke<T>(cmd: string, args: Record<string, unknown>): Promise<T> {
	return transport.invoke(cmd, args) as Promise<T>;
}

`

const footer = `
/** tauri-specta's result shape, kept so the views did not change. */
export type Result<T, E> = { status: "ok"; data: T } | { status: "error"; error: E };

/**
 * A Go method that returned an error rejects with a RuntimeError whose cause is the error's
 * JSON (an IpcError); an in-memory transport rejects with the IpcError itself. Anything else
 * (unknown method, bad arguments, no runtime) is rethrown.
 */
async function typedError<T, E>(result: Promise<T>): Promise<Result<T, E>> {
	try {
		return { status: "ok", data: await result };
	} catch (e) {
		if (e instanceof Error) {
			const cause = (e as { cause?: unknown }).cause;
			if (e.name === "RuntimeError" && cause !== undefined) return { status: "error", error: cause as E };
			throw e;
		}
		return { status: "error", error: e as E };
	}
}

/** An event with Tauri's listener shape: the callback gets ` + "`{ event, payload }`" + `. */
function makeEvent<T>(name: string) {
	return {
		listen: (cb: (event: { event: string; payload: T }) => void): Promise<() => void> =>
			transport.listen(name, (payload) => cb({ event: name, payload: payload as T })),
	};
}
`

type gen struct {
	spec        Spec
	methodTable []string
	named       map[string]reflect.Type // TypeScript name -> Go type, for every named type referenced
	order       []string
	docs        map[string]*pkgDocs
}

var (
	errorType   = reflect.TypeFor[error]()
	contextType = reflect.TypeFor[context.Context]()
	timeType    = reflect.TypeFor[time.Time]()
)

// commands renders one `commands` entry per exported service method, in source order.
func (g *gen) commands() ([]string, error) {
	svc := g.spec.Service
	ptr := reflect.PointerTo(svc)
	pd, err := g.pkg(svc.PkgPath())
	if err != nil {
		return nil, err
	}
	byName := map[string]methodDecl{}
	for _, d := range pd.methods[svc.Name()] {
		byName[d.name] = d
	}
	// Every exported method is a command; each needs its source for parameter names.
	var decls []methodDecl
	for i := range ptr.NumMethod() {
		d, ok := byName[ptr.Method(i).Name]
		if !ok {
			return nil, fmt.Errorf("%s.%s: no source found for the method (parameter names come from it)", svc, ptr.Method(i).Name)
		}
		decls = append(decls, d)
	}
	slices.SortFunc(decls, func(a, b methodDecl) int { return cmp.Compare(a.pos, b.pos) })
	fqn := svc.PkgPath() + "." + svc.Name()

	var out, table []string
	for _, d := range decls {
		m, _ := ptr.MethodByName(d.name)
		ft := m.Type // receiver is In(0)
		var params []string
		var args []string
		names := d.params
		in := make([]reflect.Type, 0, ft.NumIn()-1)
		for i := 1; i < ft.NumIn(); i++ {
			in = append(in, ft.In(i))
		}
		if len(in) > 0 && in[0] == contextType {
			in = in[1:]
			if len(names) > 0 {
				names = names[1:]
			}
		}
		if len(names) != len(in) {
			return nil, fmt.Errorf("%s: could not read parameter names from source", d.name)
		}
		for i, t := range in {
			ts, err := g.ref(t, de)
			if err != nil {
				return nil, fmt.Errorf("%s(%s): %w", d.name, names[i], err)
			}
			params = append(params, names[i]+": "+ts)
			args = append(args, names[i])
		}

		var result string
		fallible := false
		switch ft.NumOut() {
		case 0:
			result = "null"
		case 1:
			if ft.Out(0) == errorType {
				result, fallible = "null", true
			} else if result, err = g.ref(ft.Out(0), ser); err != nil {
				return nil, fmt.Errorf("%s result: %w", d.name, err)
			}
		case 2:
			if ft.Out(1) != errorType {
				return nil, fmt.Errorf("%s: second result must be error", d.name)
			}
			fallible = true
			if result, err = g.ref(ft.Out(0), ser); err != nil {
				return nil, fmt.Errorf("%s result: %w", d.name, err)
			}
		default:
			return nil, fmt.Errorf("%s: too many results", d.name)
		}

		cmd := snake(d.name)
		call := fmt.Sprintf("invoke<%s>(%q, { %s })", result, cmd, strings.Join(args, ", "))
		if len(args) == 0 {
			call = fmt.Sprintf("invoke<%s>(%q, {})", result, cmd)
		}
		if fallible {
			call = fmt.Sprintf("typedError<%s, IpcError_Serialize>(%s)", result, call)
		}
		out = append(out, jsdoc(d.doc, "\t")+fmt.Sprintf("\t%s: (%s) => %s,\n", lowerFirst(d.name), strings.Join(params, ", "), call))
		quoted := make([]string, len(args))
		for i, a := range args {
			quoted[i] = fmt.Sprintf("%q", a)
		}
		table = append(table, fmt.Sprintf("\t%s: [%q, [%s]],\n", cmd, fqn+"."+d.name, strings.Join(quoted, ", ")))
	}
	g.methodTable = table
	return out, nil
}

// snake turns a Go method name into the Rust-era command name (`GetSettings` -> `get_settings`),
// which the transport, the test mocks and the browser preview use.
func snake(name string) string {
	var b strings.Builder
	r := []rune(name)
	for i, c := range r {
		if unicode.IsUpper(c) {
			if i > 0 && (unicode.IsLower(r[i-1]) || (i+1 < len(r) && unicode.IsLower(r[i+1]))) {
				b.WriteByte('_')
			}
			c = unicode.ToLower(c)
		}
		b.WriteRune(c)
	}
	return b.String()
}

// Variants of a struct type, as tauri-specta named them: what the backend sends
// (`_Serialize`, used for results and event payloads) and what it accepts (`_Deserialize`,
// used for parameters). Inside each variant, nested structs use the same variant.
const (
	plain = ""
	ser   = "_Serialize"
	de    = "_Deserialize"
)

// ref returns the TypeScript for t where it is used, registering named types for declaration.
func (g *gen) ref(t reflect.Type, variant string) (string, error) {
	if _, ok := g.spec.Literal[t]; ok {
		return g.use(t), nil
	}
	if t == timeType {
		return "string", nil
	}
	switch t.Kind() {
	case reflect.Pointer:
		inner, err := g.ref(t.Elem(), variant)
		return inner + " | null", err
	case reflect.Slice, reflect.Array:
		inner, err := g.ref(t.Elem(), variant)
		if strings.Contains(inner, "|") {
			inner = "(" + inner + ")"
		}
		return inner + "[]", err
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", fmt.Errorf("map key %s: only string keys have a JSON object form", t.Key())
		}
		inner, err := g.ref(t.Elem(), variant)
		return "{ [key in string]: " + inner + " }", err
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		if t.Name() != "" && t.PkgPath() != "" {
			return "", fmt.Errorf("%s: named number type needs a Literal entry", t)
		}
		return "number", nil
	case reflect.Float32, reflect.Float64:
		// The JSON writer emits NaN and infinities as null, as serde_json does (and as the
		// tauri-specta types said).
		return "number | null", nil
	case reflect.String:
		if t.PkgPath() != "" {
			return "", fmt.Errorf("%s: string enum needs a Literal entry", t)
		}
		return "string", nil
	case reflect.Interface:
		return "unknown", nil
	case reflect.Struct:
		if t.Name() == "" {
			return "", fmt.Errorf("anonymous struct %s: give it a name", t)
		}
		return g.use(t) + variant, nil
	}
	return "", fmt.Errorf("unsupported type %s", t)
}

// use registers a named type and returns its TypeScript name.
func (g *gen) use(t reflect.Type) string {
	name := t.Name()
	if prev, ok := g.named[name]; ok {
		if prev != t {
			// Reported by declarations(); keep going so all clashes show up at once.
			g.named[name+"\x00"+t.PkgPath()] = t
		}
		return name
	}
	g.named[name] = t
	g.order = append(g.order, name)
	return name
}

// declarations renders every registered type, alphabetically. Declaring a struct can register
// more types, so this loops until nothing new appears.
func (g *gen) declarations() (string, error) {
	done := map[string]string{}
	for {
		var pending []string
		for _, n := range g.order {
			if _, ok := done[n]; !ok {
				pending = append(pending, n)
			}
		}
		if len(pending) == 0 {
			break
		}
		for _, n := range pending {
			decl, err := g.declare(g.named[n])
			if err != nil {
				return "", err
			}
			done[n] = decl
		}
	}
	for k, t := range g.named {
		if strings.Contains(k, "\x00") {
			return "", fmt.Errorf("two Go types are both called %s (%s and %s)", t.Name(), g.named[t.Name()].PkgPath(), t.PkgPath())
		}
	}
	names := make([]string, 0, len(done))
	for n := range done {
		names = append(names, n)
	}
	slices.Sort(names)
	var b strings.Builder
	for _, n := range names {
		b.WriteString(done[n])
		b.WriteString("\n")
	}
	return b.String(), nil
}

// declare renders one named type. Structs get the plain name plus tauri-specta's
// `_Serialize`/`_Deserialize` names, which the views import; in the `_Deserialize` form,
// fields the backend fills in when missing (pointers, `ts:"optional"`) are optional.
func (g *gen) declare(t reflect.Type) (string, error) {
	typeDoc := g.typeDoc(t)
	if lit, ok := g.spec.Literal[t]; ok {
		return fmt.Sprintf("%sexport type %s = %s;\n", jsdoc(typeDoc, ""), t.Name(), lit), nil
	}
	fields, err := g.fields(t)
	if err != nil {
		return "", err
	}
	name := t.Name()
	ser := object(fields, false)
	de := object(fields, true)
	var b strings.Builder
	b.WriteString(jsdoc(typeDoc, ""))
	if ser == de {
		fmt.Fprintf(&b, "export type %s = %s;\n", name, ser)
		fmt.Fprintf(&b, "export type %s_Serialize = %s;\nexport type %s_Deserialize = %s;\n", name, name, name, name)
	} else {
		fmt.Fprintf(&b, "export type %s = %s_Serialize | %s_Deserialize;\n", name, name, name)
		fmt.Fprintf(&b, "export type %s_Serialize = %s;\n", name, ser)
		fmt.Fprintf(&b, "export type %s_Deserialize = %s;\n", name, de)
	}
	return b.String(), nil
}

type field struct {
	name, ser, de, doc string
	optional           bool // may be left out when sent to the backend
}

func object(fields []field, deserialize bool) string {
	if len(fields) == 0 {
		return "Record<string, never>"
	}
	var b strings.Builder
	b.WriteString("{\n")
	for _, f := range fields {
		b.WriteString(jsdoc(f.doc, "\t"))
		opt := ""
		if deserialize && f.optional {
			opt = "?"
		}
		ts := f.ser
		if deserialize {
			ts = f.de
		}
		fmt.Fprintf(&b, "\t%s%s: %s,\n", f.name, opt, ts)
	}
	b.WriteString("}")
	return b.String()
}

// fields lists a struct's JSON fields, flattening embedded structs without a json name as
// encoding/json does.
func (g *gen) fields(t reflect.Type) ([]field, error) {
	var out []field
	for i := range t.NumField() {
		sf := t.Field(i)
		tag := sf.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if sf.Anonymous && name == "" {
			et := sf.Type
			if et.Kind() == reflect.Pointer {
				et = et.Elem()
			}
			if et.Kind() == reflect.Struct {
				if _, lit := g.spec.Literal[et]; !lit {
					inner, err := g.fields(et)
					if err != nil {
						return nil, err
					}
					out = append(out, inner...)
					continue
				}
			}
		}
		if !sf.IsExported() {
			continue
		}
		if name == "" {
			name = sf.Name
		}
		tsSer, err := g.ref(sf.Type, ser)
		if err != nil {
			return nil, fmt.Errorf("%s.%s: %w", t.Name(), sf.Name, err)
		}
		tsDe, err := g.ref(sf.Type, de)
		if err != nil {
			return nil, fmt.Errorf("%s.%s: %w", t.Name(), sf.Name, err)
		}
		if strings.Contains(opts, "string") {
			tsSer, tsDe = "string", "string"
		}
		tsTag := sf.Tag.Get("ts")
		if over, ok := strings.CutPrefix(tsTag, "type="); ok {
			tsSer, tsDe = over, over
		}
		out = append(out, field{
			name:     name,
			ser:      tsSer,
			de:       tsDe,
			doc:      g.fieldDoc(t, sf.Name),
			optional: sf.Type.Kind() == reflect.Pointer || tsTag == "optional",
		})
	}
	return out, nil
}

// --- doc comments and parameter names from source ---

type methodDecl struct {
	name   string
	params []string
	doc    string
	pos    token.Pos
}

type pkgDocs struct {
	types   map[string]string            // type name -> doc
	fields  map[string]map[string]string // type name -> field name -> doc
	methods map[string][]methodDecl      // receiver type name -> methods
}

func (g *gen) pkg(path string) (*pkgDocs, error) {
	if pd, ok := g.docs[path]; ok {
		return pd, nil
	}
	pd := &pkgDocs{types: map[string]string{}, fields: map[string]map[string]string{}, methods: map[string][]methodDecl{}}
	g.docs[path] = pd
	rel, ok := strings.CutPrefix(path, g.spec.ModulePath)
	if g.spec.ModulePath == "" || !ok || (rel != "" && !strings.HasPrefix(rel, "/")) {
		return pd, nil // outside the module (stdlib, dependencies): no docs
	}
	dir := filepath.Join(g.spec.ModuleDir, filepath.FromSlash(strings.TrimPrefix(rel, "/")))
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", dir, err)
	}
	fset := token.NewFileSet()
	var files []*ast.File
	for _, e := range entries {
		n := e.Name()
		if e.IsDir() || !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, n), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		files = append(files, f)
		for _, d := range f.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv == nil || len(fd.Recv.List) != 1 {
				continue
			}
			recv := fd.Recv.List[0].Type
			if star, ok := recv.(*ast.StarExpr); ok {
				recv = star.X
			}
			id, ok := recv.(*ast.Ident)
			if !ok {
				continue
			}
			var params []string
			for _, p := range fd.Type.Params.List {
				if len(p.Names) == 0 {
					params = append(params, "_")
				}
				for _, n := range p.Names {
					params = append(params, n.Name)
				}
			}
			pd.methods[id.Name] = append(pd.methods[id.Name], methodDecl{
				name: fd.Name.Name, params: params, doc: fd.Doc.Text(), pos: fd.Pos(),
			})
		}
	}
	if len(files) == 0 {
		return pd, nil
	}
	p, err := doc.NewFromFiles(fset, files, path, doc.PreserveAST|doc.AllDecls)
	if err != nil {
		return nil, err
	}
	for _, dt := range p.Types {
		pd.types[dt.Name] = dt.Doc
		for _, spec := range dt.Decl.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			if ts.Name.Name != dt.Name {
				continue
			}
			st, ok := ts.Type.(*ast.StructType)
			if !ok {
				continue
			}
			fm := map[string]string{}
			for _, f := range st.Fields.List {
				for _, n := range f.Names {
					fm[n.Name] = f.Doc.Text()
				}
			}
			pd.fields[dt.Name] = fm
		}
	}
	return pd, nil
}

func (g *gen) typeDoc(t reflect.Type) string {
	pd, err := g.pkg(t.PkgPath())
	if err != nil {
		return ""
	}
	return pd.types[t.Name()]
}

func (g *gen) fieldDoc(t reflect.Type, name string) string {
	pd, err := g.pkg(t.PkgPath())
	if err != nil {
		return ""
	}
	return pd.fields[t.Name()][name]
}

// jsdoc renders a Go doc comment as a JSDoc block.
func jsdoc(text, indent string) string {
	text = strings.TrimSpace(text)
	if text == "" {
		return ""
	}
	text = strings.ReplaceAll(text, "*/", "*\\/")
	lines := strings.Split(text, "\n")
	if len(lines) == 1 {
		return indent + "/** " + lines[0] + " */\n"
	}
	var b strings.Builder
	b.WriteString(indent + "/**\n")
	for _, l := range lines {
		b.WriteString(strings.TrimRight(indent+" * "+l, " ") + "\n")
	}
	b.WriteString(indent + " */\n")
	return b.String()
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

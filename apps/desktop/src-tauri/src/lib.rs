//! Tauri shell. Wiring only: business logic lives in the crates.
pub mod events;
pub mod ipc;
pub mod overlay;
pub mod state;

use tauri_specta::{Builder, collect_commands, collect_events};

/// Single place listing every command and event. Used by `run()` and by `export_bindings()`.
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            ipc::get_settings,
            ipc::save_settings,
            ipc::get_diagnostics,
            ipc::list_leagues,
            ipc::price_check,
            ipc::query_price,
            ipc::open_trade,
            ipc::hide_overlay,
            ipc::set_overlay_pinned,
            ipc::open_settings,
            ipc::rebind_hotkey,
        ])
        .events(collect_events![
            events::ItemCopied,
            events::PriceReady,
            events::PriceFailed,
            events::SettingsChanged,
            events::OverlayState,
        ])
        .dangerously_cast_bigints_to_number()
}

/// Write `web/src/bindings.ts`.
pub fn export_bindings(path: &std::path::Path) -> Result<(), String> {
    specta_builder()
        .export(
            specta_typescript::Typescript::default().header(
                "// @ts-nocheck\n/* eslint-disable */\n// GENERATED by `cargo xtask gen` (tauri-specta). Do not edit.",
            ),
            path,
        )
        .map_err(|e| e.to_string())
}

pub fn run() {
    let builder = specta_builder();
    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .manage(state::AppState::new())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running kalandra");
}

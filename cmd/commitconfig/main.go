// Command commitconfig generates .commitlintrc.json and docs/contributing/commit-message.md
// from .commit-config.toml, the single list of conventional-commit types and scopes.
//
//	go run ./cmd/commitconfig          write both files
//	go run ./cmd/commitconfig -check   fail when either is out of date
//
// `go generate ./...` runs it too.
package main

//go:generate go run . -root ../..

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/knadh/koanf/parsers/toml/v2"
	"github.com/knadh/koanf/providers/file"
	"github.com/knadh/koanf/v2"
)

const generated = "GENERATED by `go generate ./...` (cmd/commitconfig) from .commit-config.toml; do not edit."

// config is .commit-config.toml.
type config struct {
	HeaderMaxLength int
	Types, Scopes   map[string]string
}

func load(path string) (config, error) {
	k := koanf.New(".")
	if err := k.Load(file.Provider(path), toml.Parser()); err != nil {
		return config{}, err
	}
	c := config{HeaderMaxLength: k.Int("header_max_length"), Types: k.StringMap("types"), Scopes: k.StringMap("scopes")}
	if c.HeaderMaxLength <= 0 || len(c.Types) == 0 || len(c.Scopes) == 0 {
		return config{}, fmt.Errorf("%s: header_max_length, [types] and [scopes] are required", path)
	}
	return c, nil
}

// commitlintrc renders .commitlintrc.json; map keys come out sorted.
func commitlintrc(c config) ([]byte, error) {
	rule := func(args ...any) []any { return append([]any{2}, args...) }
	doc := map[string]any{
		"$comment": generated,
		"extends":  []string{"@commitlint/config-conventional"},
		"rules": map[string]any{
			"header-max-length":    rule("always", c.HeaderMaxLength),
			"type-enum":            rule("always", slices.Sorted(maps.Keys(c.Types))),
			"scope-enum":           rule("always", slices.Sorted(maps.Keys(c.Scopes))),
			"scope-case":           rule("always", "lower-case"),
			"subject-case":         rule("always", "lower-case"),
			"subject-full-stop":    rule("never", "."),
			"body-leading-blank":   rule("always"),
			"footer-leading-blank": rule("always"),
		},
	}
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// markdown renders docs/contributing/commit-message.md.
func markdown(c config) []byte {
	var s strings.Builder
	fmt.Fprintf(&s, "<!-- %s -->\n# Commit message guidelines\n\n", generated)
	fmt.Fprintf(&s, "Header: `<type>(<scope>): <summary>`, at most %d characters, imperative mood, lowercase, no trailing period.\n", c.HeaderMaxLength)
	s.WriteString("The body explains **why**. Footers: `BREAKING CHANGE: <migration>`, `Fixes #<n>`.\n")
	s.WriteString("Reverts: `revert: <original header>` with body `This reverts commit <SHA>.`\n")
	table := func(title, column string, rows map[string]string) {
		fmt.Fprintf(&s, "\n## %s\n\n| %s | Description |\n| --- | --- |\n", title, column)
		for _, k := range slices.Sorted(maps.Keys(rows)) {
			fmt.Fprintf(&s, "| `%s` | %s |\n", k, rows[k])
		}
	}
	table("Types", "Type", c.Types)
	table("Scopes", "Scope", c.Scopes)
	return []byte(s.String())
}

func run(root string, check bool) error {
	c, err := load(filepath.Join(root, ".commit-config.toml"))
	if err != nil {
		return err
	}
	rc, err := commitlintrc(c)
	if err != nil {
		return err
	}
	outputs := []struct {
		path string
		data []byte
	}{
		{filepath.Join(root, ".commitlintrc.json"), rc},
		{filepath.Join(root, "docs", "contributing", "commit-message.md"), markdown(c)},
	}
	var stale []string
	for _, o := range outputs {
		if check {
			if have, err := os.ReadFile(o.path); err != nil || !bytes.Equal(have, o.data) {
				stale = append(stale, o.path)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(o.path), 0o777); err != nil {
			return err
		}
		if err := os.WriteFile(o.path, o.data, 0o666); err != nil {
			return err
		}
	}
	if len(stale) > 0 {
		return fmt.Errorf("out of date (run `go run ./cmd/commitconfig`): %s", strings.Join(stale, ", "))
	}
	return nil
}

func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "fail when the generated files are out of date instead of writing them")
	flag.Parse()
	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, "commitconfig:", err)
		os.Exit(1)
	}
}
